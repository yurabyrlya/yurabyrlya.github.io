#!/usr/bin/env node
// Generates README.md (the CV summary shown on GitHub) from content/cv-data.js.
// Usage: node scripts/readme.mjs          write README.md
//        node scripts/readme.mjs --check  exit 1 if README.md is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { loadCV, root } from './lib.mjs';

const C = loadCV(), P = C.person;
const SITE = 'https://yurabyrlya.github.io/';
const fmt = d => new Date(d + '-01T00:00:00Z').toLocaleDateString('en-GB', { month: 'short', year: 'numeric', timeZone: 'UTC' });
const newest = (a, b) => b.date.localeCompare(a.date);
const cell = s => String(s).replace(/\|/g, '\\|');
const eraName = e => e.company + (e.product ? ' · ' + e.product : '');

const block = e => {
  const ms = C.milestones.filter(m => m.era === e.id).sort(newest);
  return ms.length ? [`### ${eraName(e)}`, '', `*${e.role} · ${e.period}*`, '', '| When | Highlight | Result |', '|---|---|---|',
    ...ms.map(m => `| ${fmt(m.date)} | ${m.icon} **${cell(m.title)}**<br>${cell(m.oneLiner)} | ${m.metric ? `**${cell(m.metric.value)}** ${cell(m.metric.label)}` : cell(m.star.r[0])} |`), ''] : [];
};

const md = [
  '<!-- GENERATED by scripts/readme.mjs from content/cv-data.js. Do not edit by hand. -->',
  `# ${P.name}`, '', `**${P.title}** (${P.since}) · ${P.location}`, '',
  `[![View interactive CV](https://img.shields.io/badge/View-Interactive%20CV-4f46e5?style=for-the-badge)](${SITE}) [![LinkedIn](https://img.shields.io/badge/LinkedIn-iuri--birlea-0a66c2?style=for-the-badge&logo=linkedin)](${P.linkedin})`, '',
  `> ${P.tagline}`, '',
  `**Companies:** ${P.company}. *My Utilita* and *MyUtilita v4* are Utilita products I built at Procode.`, '',
  '## Key results', '', '| | |', '|---|---|',
  ...P.highlights.map(h => `| ${h.icon} **${cell(h.strong)}** | ${cell(h.text)} |`),
  '',
  '## Core skills', '', P.stack.map(s => '`' + s + '`').join(' · '), '',
  '## Experience', '', ...C.eras.filter(e => e.section === 'experience').flatMap(block),
  '## Separate project', '', ...C.eras.filter(e => e.section === 'project').flatMap(block),
  '## Lessons learned', '', ...C.growth.map(g => `- **${g.title}:** ${g.lesson}`), '',
  '## Want the full story?', '',
  `- **[Interactive CV](${SITE})**: search, filter by skill, and a full **STAR story** (Situation, Task, Action, Result) for every highlight.`,
  '- **Print / PDF**: a compact, text-only version from the site.',
  '- **Copy for LLM**: the whole CV as Markdown from the site, ready to paste into an AI assistant.', '',
  '---', '', '<details><summary>About this repository</summary>', '',
  'Static site: plain HTML, the Tailwind CDN and vanilla JavaScript, with no build step. Content lives in `content/cv-data.js`; this README is generated from it by `scripts/readme.mjs`. Rules are in [docs/STYLE-GUIDE.md](./docs/STYLE-GUIDE.md); AI agents start at [AGENTS.md](./AGENTS.md).', '',
  '</details>', ''
].join('\n');

const file = join(root, 'README.md');
if (process.argv.includes('--check')) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (current !== md) { console.error('✖ README.md is out of date. Run: node scripts/readme.mjs'); process.exit(1); }
  console.log('✔ README.md is up to date');
} else {
  writeFileSync(file, md);
  console.log('✔ README.md regenerated');
}
